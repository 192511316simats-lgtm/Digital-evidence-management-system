import PDFDocument from 'pdfkit';
import type { CustodyValidationResult } from './crypto';

export interface ForensicReportData {
  reportId: string;
  generatedAt: string;
  generatedBy: {
    name: string;
    email: string;
    badgeNumber: string;
    role: string;
  };
  caseRecord: {
    case_code: string;
    title: string;
    description: string;
    category: string;
    priority: string;
    status: string;
    created_at: string;
  };
  assignedInvestigators: Array<{
    name: string;
    badge_number: string;
    email: string;
  }>;
  evidence: {
    evidence_code: string;
    original_filename: string;
    file_size: number;
    mime_type: string;
    sha256_hash: string;
    uploaded_at: string;
    uploader_name: string;
    uploader_badge: string;
    encryption_status: string;
    integrity_status: string;
    signature_status: string;
  };
  encryption: {
    aes_algorithm: string;
    iv_hex: string;
    auth_tag_hex: string;
    rsa_algorithm: string;
    rsa_key_bits: number;
    rsa_key_fingerprint: string;
    encrypted_size: number;
    encrypted_at: string;
  } | null;
  latestIntegrity: {
    expected_sha256: string;
    calculated_sha256: string;
    status: string;
    details: string;
    verified_at: string;
    verifier_name: string;
    verifier_badge: string;
  } | null;
  latestSignature: {
    algorithm: string;
    key_fingerprint: string;
    signature_b64: string;
    signed_at: string;
    last_verified_at: string | null;
    last_verification_result: string | null;
    signer_name: string;
    signer_badge: string;
  } | null;
  custodyEvents: Array<{
    id: number;
    event_type: string;
    timestamp: string;
    description: string;
    actor_name: string;
    actor_badge: string;
    previous_event_hash: string;
    current_event_hash: string;
  }>;
  custodyValidation: CustodyValidationResult;
}

export function buildForensicReportPdf(data: ForensicReportData): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({
      size: 'A4',
      margin: 48,
      info: {
        Title: `VERITAS Forensic Report - ${data.evidence.evidence_code}`,
        Author: `${data.generatedBy.name} (${data.generatedBy.badgeNumber})`,
        Subject: `Digital Evidence Report for ${data.caseRecord.case_code}`,
        Creator: 'VERITAS Digital Evidence Management System',
      },
    });

    const chunks: Buffer[] = [];
    doc.on('data', (chunk) => chunks.push(Buffer.from(chunk)));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);

    const primary = '#252A27';
    const secondary = '#536B58';
    const bronze = '#A88755';
    const muted = '#666B66';
    const border = '#D8DAD3';

    // Header Banner
    doc.rect(48, 42, 499, 58).fill('#202522');
    doc.fillColor('#F5F4EF').font('Helvetica-Bold').fontSize(16).text('VERITAS | FORENSICS', 64, 56);
    doc
      .fillColor('#A88755')
      .font('Helvetica')
      .fontSize(9)
      .text('DIGITAL EVIDENCE & CRYPTOGRAPHIC INTEGRITY REPORT', 64, 78);

    doc
      .fillColor('#D8DAD3')
      .font('Helvetica')
      .fontSize(8)
      .text(`REPORT ID: ${data.reportId}`, 350, 58, { align: 'right', width: 180 })
      .text(`GENERATED: ${data.generatedAt}`, 350, 72, { align: 'right', width: 180 });

    doc.y = 116;

    const sectionTitle = (title: string) => {
      if (doc.y > 700) doc.addPage();
      doc.moveDown(0.5);
      doc.fillColor(secondary).font('Helvetica-Bold').fontSize(11).text(title.toUpperCase());
      doc
        .moveTo(48, doc.y + 2)
        .lineTo(547, doc.y + 2)
        .strokeColor(border)
        .lineWidth(1)
        .stroke();
      doc.moveDown(0.4);
    };

    const kv = (label: string, value: string, mono = false) => {
      if (doc.y > 745) doc.addPage();
      const y = doc.y;
      doc.fillColor(muted).font('Helvetica-Bold').fontSize(8.5).text(label, 48, y, { width: 155 });
      doc
        .fillColor(primary)
        .font(mono ? 'Courier' : 'Helvetica')
        .fontSize(mono ? 8 : 9)
        .text(value || 'N/A', 208, y, { width: 339 });
      doc.moveDown(0.25);
    };

    // 1. Report Metadata & Officer
    sectionTitle('1. Report Authorization & Case Record');
    kv('Generated By', `${data.generatedBy.name} (${data.generatedBy.badgeNumber}) · ${data.generatedBy.role}`);
    kv('Officer Email', data.generatedBy.email);
    kv('Case Identifier', `${data.caseRecord.case_code} — ${data.caseRecord.title}`);
    kv('Category / Priority', `${data.caseRecord.category} · Priority: ${data.caseRecord.priority} · Status: ${data.caseRecord.status}`);
    kv(
      'Assigned Investigators',
      data.assignedInvestigators.length > 0
        ? data.assignedInvestigators.map((i) => `${i.name} (${i.badge_number})`).join(', ')
        : 'None assigned'
    );
    kv('Case Description', data.caseRecord.description);

    // 2. Evidence Details
    sectionTitle('2. Digital Evidence Artifact');
    kv('Evidence ID', data.evidence.evidence_code, true);
    kv('Original Filename', data.evidence.original_filename);
    kv('MIME Type / File Size', `${data.evidence.mime_type} · ${data.evidence.file_size.toLocaleString()} bytes`);
    kv('Acquired By', `${data.evidence.uploader_name} (${data.evidence.uploader_badge})`);
    kv('Acquisition Timestamp', data.evidence.uploaded_at, true);
    kv('Expected SHA-256 Digest', data.evidence.sha256_hash, true);

    // 3. Hybrid Cryptography Metadata
    sectionTitle('3. Hybrid Cryptography & Vault Protection');
    kv('Encryption Status', data.evidence.encryption_status);
    if (data.encryption) {
      kv('Symmetric Cipher', `${data.encryption.aes_algorithm} (Authenticated Encryption)`);
      kv('Key Wrapping', `${data.encryption.rsa_algorithm} (${data.encryption.rsa_key_bits}-bit)`);
      kv('Vault Key Fingerprint', data.encryption.rsa_key_fingerprint, true);
      kv('Nonce / IV (Hex)', data.encryption.iv_hex, true);
      kv('GCM Auth Tag (Hex)', data.encryption.auth_tag_hex, true);
      kv('Encrypted Size', `${data.encryption.encrypted_size.toLocaleString()} bytes`);
      kv('Encrypted Timestamp', data.encryption.encrypted_at, true);
    } else {
      kv('Encryption Details', 'No encryption metadata found.');
    }

    // 4. Integrity Verification
    sectionTitle('4. SHA-256 Hash Integrity Verification');
    kv('Current Integrity State', data.evidence.integrity_status);
    if (data.latestIntegrity) {
      kv('Last Verification Result', data.latestIntegrity.status);
      kv('Verified By', `${data.latestIntegrity.verifier_name} (${data.latestIntegrity.verifier_badge})`);
      kv('Verification Timestamp', data.latestIntegrity.verified_at, true);
      kv('Expected SHA-256', data.latestIntegrity.expected_sha256, true);
      kv('Recalculated SHA-256', data.latestIntegrity.calculated_sha256, true);
      kv('Verification Notes', data.latestIntegrity.details);
    } else {
      kv('Verification History', 'Integrity verification has not yet been executed for this artifact.');
    }

    // 5. Digital Signature
    sectionTitle('5. RSA-PSS Digital Signature Verification');
    kv('Current Signature State', data.evidence.signature_status);
    if (data.latestSignature) {
      kv('Signature Algorithm', data.latestSignature.algorithm);
      kv('Signer', `${data.latestSignature.signer_name} (${data.latestSignature.signer_badge})`);
      kv('Signing Key Fingerprint', data.latestSignature.key_fingerprint, true);
      kv('Signed Timestamp', data.latestSignature.signed_at, true);
      kv('Last Verification', data.latestSignature.last_verified_at || 'Not yet verified', true);
      kv('Signature Digest (Preview)', `${data.latestSignature.signature_b64.slice(0, 72)}...`, true);
    } else {
      kv('Signature Record', 'No digital signature manifest attached to this evidence item.');
    }

    // 6. Chain of Custody
    sectionTitle('6. Hash-Linked Chain of Custody History');
    kv(
      'Chain Integrity Check',
      data.custodyValidation.valid
        ? `VALID (${data.custodyValidation.totalEvents} linked events verified)`
        : `BROKEN (${data.custodyValidation.reason || 'Hash mismatch detected'})`
    );
    doc.moveDown(0.3);

    for (const ev of data.custodyEvents) {
      if (doc.y > 710) doc.addPage();
      const boxY = doc.y;
      doc.fillColor(bronze).font('Helvetica-Bold').fontSize(8.5).text(
        `#${ev.id} · ${ev.event_type} · ${ev.timestamp}`,
        48,
        boxY
      );
      doc.fillColor(primary).font('Helvetica').fontSize(8.5).text(
        `${ev.description} — Actor: ${ev.actor_name} (${ev.actor_badge})`,
        58,
        doc.y + 1,
        { width: 489 }
      );
      doc.fillColor(muted).font('Courier').fontSize(7).text(
        `PREV: ${ev.previous_event_hash.slice(0, 32)}...  CURR: ${ev.current_event_hash.slice(0, 32)}...`,
        58,
        doc.y + 1,
        { width: 489 }
      );
      doc.moveDown(0.35);
    }

    // Footer disclaimer
    if (doc.y > 740) doc.addPage();
    doc.moveDown(0.8);
    doc
      .fillColor(muted)
      .font('Helvetica')
      .fontSize(7.5)
      .text(
        'Note: This report was generated directly from VERITAS SQLite database records and live cryptographic metadata. Hash-linked custody events allow detection of post-hoc record modification within database storage.',
        48,
        doc.y,
        { width: 499 }
      );

    doc.end();
  });
}
